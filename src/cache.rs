//! The `.rbview/` cache: where views live, when a cached view is still valid, and `rbview build`.
//! The rules are in `docs/spec/cache.md`; the speed budget in `docs/performance.md`.

use crate::{GEN_VERSION, Kind, KindMap, PRELUDE, collect_kinds, generate_hashed, hash_src};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::fs;
use std::io::{self, Read};
use std::path::{Path, PathBuf};
use std::sync::OnceLock;
use std::sync::atomic::{AtomicU64, AtomicUsize, Ordering};
use std::time::Instant;

pub const CACHE_DIR: &str = ".rbview";

/// How much of a map file `build` reads to validate it: enough for `version`, `hash` and `deps`.
const MAP_HEAD: usize = 16 * 1024;

pub fn find_root(start: &Path) -> PathBuf {
    let start = start.canonicalize().unwrap_or(start.to_path_buf());
    let dir = if start.is_file() { start.parent().unwrap().to_path_buf() } else { start };
    // 1. an existing .rbview  2. a git repo root  3. the outermost Cargo.toml
    for marker in [CACHE_DIR, ".git"] {
        let mut d = Some(dir.as_path());
        while let Some(p) = d {
            if p.join(marker).exists() {
                return p.to_path_buf();
            }
            d = p.parent();
        }
    }
    let mut best = dir.clone();
    let mut d = Some(dir.as_path());
    while let Some(p) = d {
        if p.join("Cargo.toml").exists() {
            best = p.to_path_buf();
        }
        d = p.parent();
    }
    best
}

/// Create `<root>/.rbview/` with its `.gitignore` and prelude. Only needed before writing.
pub fn ensure_cache_dir(root: &Path) -> PathBuf {
    let dir = root.join(CACHE_DIR);
    let _ = fs::create_dir_all(&dir);
    let gi = dir.join(".gitignore");
    if !gi.exists() {
        let _ = fs::write(&gi, "# generated by rbview — safe to delete\n*\n");
    }
    let prelude = dir.join("_prelude.rb");
    if fs::read_to_string(&prelude).ok().as_deref() != Some(PRELUDE) {
        let _ = write_atomic(&prelude, PRELUDE.as_bytes());
    }
    dir
}

/// Where the cached view for `file` lives inside `.rbview/`.
pub fn cache_path(cache: &Path, root: &Path, file: &Path) -> PathBuf {
    if let Ok(rel) = file.strip_prefix(root) {
        return cache.join(rel).with_extension("rb");
    }
    // Dependency sources: key registry crates by "<name>-<version>/..." so
    // every repo version of a crate gets its own (immutable) cache entry.
    let s = file.to_string_lossy();
    let key = if let Some(idx) = s.find("/registry/src/") {
        let after = &s[idx + "/registry/src/".len()..];
        after.split_once('/').map(|(_, rest)| rest.to_string()).unwrap_or(after.to_string())
    } else {
        s.trim_start_matches('/').to_string()
    };
    cache.join("ext").join(key).with_extension("rb")
}

fn map_path_for(rb_path: &Path) -> PathBuf {
    PathBuf::from(format!("{}.map.json", rb_path.display()))
}

/// Write via a temporary file and a rename, so a concurrent reader (another `rbview gen` for
/// the same file, which the editor runs in parallel) sees the old file or the new one, never half.
fn write_atomic(path: &Path, bytes: &[u8]) -> io::Result<()> {
    static N: AtomicU64 = AtomicU64::new(0);
    let tmp =
        PathBuf::from(format!("{}.{}-{}.tmp", path.display(), std::process::id(), N.fetch_add(1, Ordering::Relaxed)));
    fs::write(&tmp, bytes)?;
    fs::rename(&tmp, path).inspect_err(|_| {
        let _ = fs::remove_file(&tmp);
    })
}

// ---------------------------------------------------------------- symbol kinds

#[derive(Serialize, Deserialize, Default)]
struct Symbols {
    kinds: BTreeMap<String, Kind>,
}

/// Read `symbols.json`. Unknown kinds are skipped; a missing or unreadable file is an empty table.
pub fn load_kinds(cache: &Path) -> KindMap {
    use serde::de::{DeserializeSeed, Deserializer, IgnoredAny, MapAccess, Visitor};
    use std::borrow::Cow;
    use std::fmt;
    let Ok(text) = fs::read_to_string(cache.join("symbols.json")) else { return KindMap::default() };

    // Straight into the table: one pass, no intermediate map.
    struct Table(usize);
    impl<'de> Visitor<'de> for Table {
        type Value = KindMap;
        fn expecting(&self, f: &mut fmt::Formatter) -> fmt::Result {
            f.write_str("a map of type names to kinds")
        }
        fn visit_map<M: MapAccess<'de>>(self, mut m: M) -> Result<KindMap, M::Error> {
            let mut t = KindMap::with_capacity_and_hasher(self.0, Default::default());
            while let Some((name, kind)) = m.next_entry::<String, Lenient>()? {
                if let Some(kind) = kind.0 {
                    t.insert(name, kind);
                }
            }
            Ok(t)
        }
    }
    impl<'de> DeserializeSeed<'de> for Table {
        type Value = KindMap;
        fn deserialize<D: Deserializer<'de>>(self, d: D) -> Result<KindMap, D::Error> {
            d.deserialize_map(self)
        }
    }
    struct File(usize);
    impl<'de> Visitor<'de> for File {
        type Value = KindMap;
        fn expecting(&self, f: &mut fmt::Formatter) -> fmt::Result {
            f.write_str("{\"kinds\": {...}}")
        }
        fn visit_map<M: MapAccess<'de>>(self, mut m: M) -> Result<KindMap, M::Error> {
            let mut t = KindMap::default();
            while let Some(key) = m.next_key::<Cow<'de, str>>()? {
                if key == "kinds" {
                    t = m.next_value_seed(Table(self.0))?;
                } else {
                    m.next_value::<IgnoredAny>()?;
                }
            }
            Ok(t)
        }
    }
    /// A kind, or None for one this rbview doesn't know (read without allocating).
    struct Lenient(Option<Kind>);
    impl<'de> serde::Deserialize<'de> for Lenient {
        fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
            struct V;
            impl Visitor<'_> for V {
                type Value = Lenient;
                fn expecting(&self, f: &mut fmt::Formatter) -> fmt::Result {
                    f.write_str("a kind")
                }
                fn visit_str<E>(self, v: &str) -> Result<Lenient, E> {
                    Ok(Lenient(match v {
                        "struct" => Some(Kind::Struct),
                        "enum" => Some(Kind::Enum),
                        "trait" => Some(Kind::Trait),
                        _ => None,
                    }))
                }
                fn visit_unit<E>(self) -> Result<Lenient, E> {
                    Ok(Lenient(None))
                }
            }
            d.deserialize_any(V)
        }
    }
    // about 30 bytes per pretty-printed entry
    let mut de = serde_json::Deserializer::from_str(&text);
    de.deserialize_map(File(text.len() / 30)).unwrap_or_default()
}

fn write_kinds(cache: &Path, kinds: &KindMap) -> io::Result<()> {
    let sym = Symbols { kinds: kinds.iter().map(|(k, v)| (k.clone(), *v)).collect() };
    write_atomic(&cache.join("symbols.json"), serde_json::to_string_pretty(&sym).unwrap().as_bytes())
}

/// The crate-wide symbol kinds (`symbols.json`), read on first use: a cached view whose map
/// relies on no kinds is served without reading them.
pub struct Kinds {
    file: Option<PathBuf>,
    map: OnceLock<KindMap>,
}

impl Kinds {
    /// Kinds from `<cache>/symbols.json`, loaded when first needed.
    pub fn lazy(cache: &Path) -> Self {
        Kinds { file: Some(cache.to_path_buf()), map: OnceLock::new() }
    }

    pub fn ready(map: KindMap) -> Self {
        let cell = OnceLock::new();
        let _ = cell.set(map);
        Kinds { file: None, map: cell }
    }

    pub fn get(&self) -> &KindMap {
        self.map.get_or_init(|| self.file.as_deref().map(load_kinds).unwrap_or_default())
    }

    /// Whether every kind a cached view relied on is still what it assumed.
    fn agree(&self, deps: &BTreeMap<String, Option<Kind>>) -> bool {
        deps.is_empty() || {
            let k = self.get();
            deps.iter().all(|(name, want)| k.get(name) == want.as_ref())
        }
    }
}

// ---------------------------------------------------------------- one view

/// The kinds a cached map relied on, if the map was written for this `hash` by this rbview.
/// Only the start of the map is read: `version`, `hash` and `deps` are its first fields.
fn cached_deps(map: &str, hash: &str) -> Option<BTreeMap<String, Option<Kind>>> {
    let rest = map.strip_prefix(&format!("{{\"version\":{GEN_VERSION},\"hash\":\"{hash}\",\"deps\":"))?;
    // deps is a flat object of identifiers, so its first '}' closes it
    let end = rest.find('}')? + 1;
    serde_json::from_str(&rest[..end]).ok()
}

/// [`cached_deps`] reading as little of the map file as possible.
fn cached_deps_in(map_path: &Path, hash: &str) -> Option<BTreeMap<String, Option<Kind>>> {
    let mut f = fs::File::open(map_path).ok()?;
    let mut head = Vec::with_capacity(MAP_HEAD);
    (&mut f).take(MAP_HEAD as u64).read_to_end(&mut head).ok()?;
    match cached_deps(&String::from_utf8_lossy(&head), hash) {
        None if head.len() == MAP_HEAD => cached_deps(&fs::read_to_string(map_path).ok()?, hash),
        found => found,
    }
}

pub struct View {
    pub ruby: String,
    pub map_json: String,
    pub rb_path: PathBuf,
    /// Served from `.rbview/` without generating.
    pub cached: bool,
    pub parse_error: Option<String>,
}

impl View {
    /// `{"rbPath", "cached", "ruby", "map"}`: what `rbview gen --json` prints and `rbview serve`
    /// returns for a `gen` request.
    pub fn to_json(&self) -> String {
        format!(
            "{{\"rbPath\":{},\"cached\":{},\"ruby\":{},\"map\":{}}}",
            serde_json::to_string(&self.rb_path.to_string_lossy()).unwrap(),
            self.cached,
            serde_json::to_string(&self.ruby).unwrap(),
            self.map_json
        )
    }
}

/// The canonical file and cache root for a request: `root` if given, else [`find_root`].
pub fn resolve(file: &Path, root: Option<&Path>) -> io::Result<(PathBuf, PathBuf)> {
    let file = file.canonicalize()?;
    let root = root.map(Path::to_path_buf).unwrap_or_else(|| find_root(&file));
    let root = root.canonicalize().unwrap_or(root);
    Ok((file, root))
}

/// Generate (or reuse) the cached view for one file.
pub fn gen_cached(file: &Path, root: &Path, kinds: &Kinds, use_cache: bool) -> io::Result<View> {
    let src = fs::read_to_string(file)?;
    let cache = root.join(CACHE_DIR);
    let rb_path = cache_path(&cache, root, file);
    let map_path = map_path_for(&rb_path);
    let hash = hash_src(&src);
    // The map is read first: it vouches for the view, and is written after it.
    if use_cache
        && let Ok(map_json) = fs::read_to_string(&map_path)
        && cached_deps(&map_json, &hash).is_some_and(|deps| kinds.agree(&deps))
        && let Ok(ruby) = fs::read_to_string(&rb_path)
    {
        return Ok(View { ruby, map_json, rb_path, cached: true, parse_error: None });
    }
    let g = generate_hashed(&src, file, kinds.get(), hash);
    let map_json = serde_json::to_string(&g.map).unwrap();
    store(root, &rb_path, &map_path, &g.ruby, &map_json)?;
    Ok(View { ruby: g.ruby, map_json, rb_path, cached: false, parse_error: g.parse_error })
}

fn store(root: &Path, rb_path: &Path, map_path: &Path, ruby: &str, map_json: &str) -> io::Result<()> {
    ensure_cache_dir(root);
    if let Some(parent) = rb_path.parent() {
        fs::create_dir_all(parent)?;
    }
    write_atomic(rb_path, ruby.as_bytes())?;
    write_atomic(map_path, map_json.as_bytes())
}

// ---------------------------------------------------------------- build

/// Every `.rs` file under `dir`, skipping hidden folders, `target/` and `node_modules/`, sorted.
pub fn walk_rs(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(rd) = fs::read_dir(dir) else { return };
    let mut entries: Vec<_> = rd.flatten().collect();
    entries.sort_by_key(|e| e.file_name());
    for e in entries {
        let p = e.path();
        let name = e.file_name().to_string_lossy().to_string();
        if name.starts_with('.') || name == "target" || name == "node_modules" {
            continue;
        }
        if p.is_dir() {
            walk_rs(&p, out);
        } else if name.ends_with(".rs") {
            out.push(p);
        }
    }
}

/// Run `f(i)` for every `i` in `order`, on every core, starting jobs in that order (put big
/// ones first so no core is left with a long job at the end). Results come back indexed by `i`.
fn par_map<R: Send>(order: &[usize], f: impl Fn(usize) -> R + Sync) -> Vec<R> {
    let next = AtomicUsize::new(0);
    let workers = std::thread::available_parallelism().map(|n| n.get()).unwrap_or(4).min(order.len()).max(1);
    let done: Vec<(usize, R)> = std::thread::scope(|s| {
        let jobs: Vec<_> = (0..workers)
            .map(|_| {
                s.spawn(|| {
                    let mut mine = vec![];
                    while let Some(&i) = order.get(next.fetch_add(1, Ordering::Relaxed)) {
                        mine.push((i, f(i)));
                    }
                    mine
                })
            })
            .collect();
        jobs.into_iter().flat_map(|j| j.join().unwrap()).collect()
    });
    let mut out: Vec<Option<R>> = (0..order.len()).map(|_| None).collect();
    for (i, r) in done {
        out[i] = Some(r);
    }
    out.into_iter().map(|r| r.expect("every job has a result")).collect()
}

/// `.rbview/index.json`: what each file defined at its last build, keyed by source hash, so an
/// unchanged file isn't parsed again just to collect its type names.
#[derive(Serialize, Deserialize, Default)]
struct Index {
    files: BTreeMap<String, IndexEntry>,
}

#[derive(Serialize, Deserialize, Clone)]
struct IndexEntry {
    hash: String,
    defs: BTreeMap<String, Kind>,
}

fn index_key(root: &Path, file: &Path) -> String {
    file.strip_prefix(root).unwrap_or(file).to_string_lossy().to_string()
}

/// What `rbview build` did.
pub struct BuildReport {
    pub files: usize,
    pub generated: usize,
    pub unchanged: usize,
    /// Files shown as raw source (parse errors) or that couldn't be read or written.
    pub errors: Vec<String>,
    pub cache: PathBuf,
    pub elapsed: std::time::Duration,
}

impl std::fmt::Display for BuildReport {
    fn fmt(&self, f: &mut std::fmt::Formatter) -> std::fmt::Result {
        write!(
            f,
            "rbview: {} files ({} generated, {} unchanged) into {} in {:.2?}",
            self.files,
            self.generated,
            self.unchanged,
            self.cache.display(),
            self.elapsed
        )?;
        for e in &self.errors {
            write!(f, "\n  fallback (raw source): {e}")?;
        }
        Ok(())
    }
}

/// Pre-generate the view of every `.rs` file under `dir` (see docs/spec/cache.md).
pub fn cmd_build(dir: &Path, force: bool) -> BuildReport {
    let t0 = Instant::now();
    let root = find_root(dir);
    let cache = ensure_cache_dir(&root);
    let dir = dir.canonicalize().unwrap_or(dir.to_path_buf());
    let mut files = vec![];
    walk_rs(&dir, &mut files);
    let mut order: Vec<usize> = (0..files.len()).collect();
    order.sort_by_cached_key(|&i| std::cmp::Reverse(fs::metadata(&files[i]).map_or(0, |m| m.len())));

    // Pass 1: bring every view up to date against the symbol kinds of the last build, and
    // collect the types each file defines. A file is parsed at most once: when its view is stale,
    // or when it changed since the index was written.
    let index_path = cache.join("index.json");
    let old: Index = fs::read(&index_path).ok().and_then(|b| serde_json::from_slice(&b).ok()).unwrap_or_default();
    let last_kinds = Kinds::lazy(&cache);
    let pass1: Vec<io::Result<(Fresh, IndexEntry)>> = par_map(&order, |i| {
        let f = &files[i];
        let src = fs::read_to_string(f)?;
        let hash = hash_src(&src);
        let fresh = refresh(f, &root, &cache, &last_kinds, &src, &hash, force)?;
        let defs = match (&fresh.defs, old.files.get(&index_key(&root, f))) {
            (Some(defs), _) => defs.iter().map(|(k, v)| (k.clone(), *v)).collect(),
            (None, Some(e)) if e.hash == hash => e.defs.clone(),
            (None, _) => {
                let mut defs = KindMap::default();
                if let Ok(ast) = syn::parse_file(&src) {
                    collect_kinds(&ast.items, &mut defs);
                }
                proc_macro2::extra::invalidate_current_thread_spans();
                defs.into_iter().collect()
            }
        };
        Ok((fresh, IndexEntry { hash, defs }))
    });

    // index.json: keep entries for files outside `dir` that still exist; replace the rest.
    let mut index = Index {
        files: old
            .files
            .into_iter()
            .filter(|(k, _)| !root.join(k).starts_with(&dir) && root.join(k).exists())
            .collect(),
    };
    for (f, r) in files.iter().zip(&pass1) {
        if let Ok((_, e)) = r {
            index.files.insert(index_key(&root, f), e.clone());
        }
    }
    let _ = write_atomic(&index_path, serde_json::to_string(&index).unwrap().as_bytes());
    // symbols.json is what every indexed file defines. On a name defined twice, the later path
    // wins; the index is sorted, so the result is deterministic.
    let mut kinds = KindMap::default();
    for e in index.files.values() {
        kinds.extend(e.defs.iter().map(|(k, v)| (k.clone(), *v)));
    }
    let _ = write_kinds(&cache, &kinds);

    // Pass 2: regenerate the views that relied on a kind that just changed. Their deps are
    // already in memory, so nothing is read for the rest.
    let kinds = Kinds::ready(kinds);
    let stale: Vec<usize> =
        order.iter().copied().filter(|&i| matches!(&pass1[i], Ok((f, _)) if !kinds.agree(&f.deps))).collect();
    let pass2: Vec<Option<io::Result<Fresh>>> = {
        let mut out: Vec<Option<io::Result<Fresh>>> = (0..files.len()).map(|_| None).collect();
        let redone = par_map(&(0..stale.len()).collect::<Vec<_>>(), |j| {
            let f = &files[stale[j]];
            let src = fs::read_to_string(f)?;
            refresh(f, &root, &cache, &kinds, &src, &hash_src(&src), true)
        });
        for (j, r) in redone.into_iter().enumerate() {
            out[stale[j]] = Some(r);
        }
        out
    };

    let mut report = BuildReport {
        files: files.len(),
        generated: 0,
        unchanged: 0,
        errors: vec![],
        cache,
        elapsed: Default::default(),
    };
    for ((f, first), second) in files.iter().zip(pass1).zip(pass2) {
        let (generated, perr) = match (first, second) {
            (Err(e), _) | (_, Some(Err(e))) => {
                report.errors.push(format!("{}: {e}", f.display()));
                continue;
            }
            (Ok((fr, _)), None) => (fr.generated, fr.parse_error),
            (Ok(_), Some(Ok(fr))) => (true, fr.parse_error),
        };
        if generated {
            report.generated += 1;
        } else {
            report.unchanged += 1;
        }
        if let Some(e) = perr {
            report.errors.push(format!("{}: {e}", f.display()));
        }
    }
    report.elapsed = t0.elapsed();
    report
}

/// What [`refresh`] found or did for one file.
struct Fresh {
    generated: bool,
    /// The kinds the (now current) view relied on.
    deps: BTreeMap<String, Option<Kind>>,
    /// The types the file defines, when it was parsed.
    defs: Option<KindMap>,
    parse_error: Option<String>,
}

/// Bring one file's view up to date against `kinds`: reuse it if its map was written for this
/// source and every kind it relied on still holds (unless `force`), else generate it.
fn refresh(
    file: &Path,
    root: &Path,
    cache: &Path,
    kinds: &Kinds,
    src: &str,
    hash: &str,
    force: bool,
) -> io::Result<Fresh> {
    let rb_path = cache_path(cache, root, file);
    let map_path = map_path_for(&rb_path);
    if !force
        && let Some(deps) = cached_deps_in(&map_path, hash)
        && kinds.agree(&deps)
        && rb_path.exists()
    {
        return Ok(Fresh { generated: false, deps, defs: None, parse_error: None });
    }
    let g = generate_hashed(src, file, kinds.get(), hash.to_string());
    // proc-macro2 keeps every parsed file's line table in a thread-local map; let it go
    proc_macro2::extra::invalidate_current_thread_spans();
    store(root, &rb_path, &map_path, &g.ruby, &serde_json::to_string(&g.map).unwrap())?;
    Ok(Fresh { generated: true, deps: g.map.deps, defs: Some(g.defs), parse_error: g.parse_error })
}
