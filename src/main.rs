//! rbview — read Rust code as Ruby.
//!
//!   rbview gen <file.rs> [--root DIR] [--json] [--no-cache]
//!   rbview build [DIR] [--force]
//!
//! Generated views, position maps and a crate-wide symbol index live in a
//! hidden `.rbview/` folder at the repo root (like `.git` or `.idea`).

mod emit;
mod out;

use emit::{Gen, Kind};
use out::SourceMap;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::collections::HashMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::Instant;

/// Bump when the translation changes: invalidates every cached view.
const GEN_VERSION: u32 = 1;
const PRELUDE: &str = include_str!("prelude.rb");
const CACHE_DIR: &str = ".rbview";

#[derive(Serialize, Deserialize)]
struct Symbols {
    kinds: HashMap<String, String>,
}

fn kind_str(k: Kind) -> &'static str {
    match k {
        Kind::Struct => "struct",
        Kind::Enum => "enum",
        Kind::Trait => "trait",
    }
}

fn kind_parse(s: &str) -> Option<Kind> {
    match s {
        "struct" => Some(Kind::Struct),
        "enum" => Some(Kind::Enum),
        "trait" => Some(Kind::Trait),
        _ => None,
    }
}

fn hash_src(src: &str) -> String {
    let mut h = Sha256::new();
    h.update(GEN_VERSION.to_le_bytes());
    h.update(env!("RBVIEW_BUILD_ID").as_bytes());
    h.update(src.as_bytes());
    h.finalize().iter().take(16).map(|b| format!("{b:02x}")).collect()
}

/// `src/foo/bar.rs` -> ["foo", "bar"], `src/foo/mod.rs` -> ["foo"], lib.rs/main.rs/bin/* -> [].
/// Paths are taken relative to the nearest Cargo.toml, so examples/, tests/ and
/// benches/ files are crate roots (no module wrapper).
fn module_path(file: &Path) -> Vec<String> {
    let mut crate_dir = None;
    let mut d = file.parent();
    while let Some(p) = d {
        if p.join("Cargo.toml").exists() {
            crate_dir = Some(p);
            break;
        }
        d = p.parent();
    }
    let rel = match crate_dir.and_then(|c| file.strip_prefix(c).ok()) {
        Some(r) => r,
        None => return vec![],
    };
    let mut comps: Vec<String> = rel.components().map(|c| c.as_os_str().to_string_lossy().to_string()).collect();
    if comps.first().map(|s| s.as_str()) != Some("src") {
        return vec![];
    }
    comps.remove(0);
    if comps.first().is_some_and(|c| c == "bin") {
        return vec![];
    }
    if let Some(last) = comps.pop() {
        let stem = last.trim_end_matches(".rs").to_string();
        if !(comps.is_empty() && (stem == "lib" || stem == "main")) && stem != "mod" {
            comps.push(stem);
        }
    }
    comps
}

fn find_root(start: &Path) -> PathBuf {
    let start = start.canonicalize().unwrap_or(start.to_path_buf());
    let dir = if start.is_file() { start.parent().unwrap().to_path_buf() } else { start };
    // 1. an existing .rbview  2. a git repo root  3. the outermost Cargo.toml
    for marker in [CACHE_DIR, ".git"] {
        let mut d = Some(dir.as_path());
        while let Some(p) = d {
            if p.join(marker).exists() {
                return p.to_path_buf();
            }
            d = p.parent();
        }
    }
    let mut best = dir.clone();
    let mut d = Some(dir.as_path());
    while let Some(p) = d {
        if p.join("Cargo.toml").exists() {
            best = p.to_path_buf();
        }
        d = p.parent();
    }
    best
}

fn ensure_cache_dir(root: &Path) -> PathBuf {
    let dir = root.join(CACHE_DIR);
    let _ = fs::create_dir_all(&dir);
    let gi = dir.join(".gitignore");
    if !gi.exists() {
        let _ = fs::write(&gi, "# generated by rbview — safe to delete\n*\n");
    }
    let prelude = dir.join("_prelude.rb");
    if fs::read_to_string(&prelude).ok().as_deref() != Some(PRELUDE) {
        let _ = fs::write(&prelude, PRELUDE);
    }
    dir
}

/// Where the cached view for `file` lives inside `.rbview/`.
fn cache_path(cache: &Path, root: &Path, file: &Path) -> PathBuf {
    if let Ok(rel) = file.strip_prefix(root) {
        return cache.join(rel).with_extension("rb");
    }
    // Dependency sources: key registry crates by "<name>-<version>/..." so
    // every repo version of a crate gets its own (immutable) cache entry.
    let s = file.to_string_lossy();
    let key = if let Some(idx) = s.find("/registry/src/") {
        let after = &s[idx + "/registry/src/".len()..];
        after.split_once('/').map(|(_, rest)| rest.to_string()).unwrap_or(after.to_string())
    } else {
        s.trim_start_matches('/').to_string()
    };
    cache.join("ext").join(key).with_extension("rb")
}

fn load_kinds(cache: &Path) -> HashMap<String, Kind> {
    fs::read_to_string(cache.join("symbols.json"))
        .ok()
        .and_then(|s| serde_json::from_str::<Symbols>(&s).ok())
        .map(|s| s.kinds.into_iter().filter_map(|(k, v)| kind_parse(&v).map(|k2| (k, k2))).collect())
        .unwrap_or_default()
}

pub struct Generated {
    pub ruby: String,
    pub map: SourceMap,
    pub parse_error: Option<String>,
}

pub fn generate(src: &str, file: &Path, kinds: &HashMap<String, Kind>) -> Generated {
    let hash = hash_src(src);
    match syn::parse_file(src) {
        Ok(ast) => {
            let mut g = Gen::new(src, kinds);
            g.file(&ast, &module_path(file));
            Generated {
                ruby: g.out.buf,
                map: SourceMap { version: GEN_VERSION, hash, segs: g.out.segs, blocks: g.out.blocks },
                parse_error: None,
            }
        }
        Err(e) => {
            // Fall back to the raw source in a block comment, mapped line-for-line.
            let header = format!(
                "# rbview: could not parse this file ({} at line {}). Showing the Rust source.\n=begin\n",
                e,
                e.span().start().line
            );
            let offset = header.lines().count() as u32;
            let n = src.lines().count() as u32;
            let blocks = (0..n).map(|i| [i + offset, i + offset, i, i]).collect();
            Generated {
                ruby: format!("{header}{src}\n=end\n"),
                map: SourceMap { version: GEN_VERSION, hash, segs: vec![], blocks },
                parse_error: Some(e.to_string()),
            }
        }
    }
}

/// Generate (or reuse) the cached view for one file. Returns (ruby, map_json, rb_path, from_cache).
fn gen_cached(file: &Path, root: &Path, kinds: &HashMap<String, Kind>, use_cache: bool) -> std::io::Result<(String, String, PathBuf, bool, Option<String>)> {
    let src = fs::read_to_string(file)?;
    let cache = ensure_cache_dir(root);
    let rb_path = cache_path(&cache, root, file);
    let map_path = PathBuf::from(format!("{}.map.json", rb_path.display()));
    let hash = hash_src(&src);
    if use_cache {
        if let (Ok(ruby), Ok(map)) = (fs::read_to_string(&rb_path), fs::read_to_string(&map_path)) {
            if map.contains(&format!("\"hash\":\"{hash}\"")) {
                return Ok((ruby, map, rb_path, true, None));
            }
        }
    }
    let g = generate(&src, file, kinds);
    let map_json = serde_json::to_string(&g.map).unwrap();
    if let Some(parent) = rb_path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&rb_path, &g.ruby)?;
    fs::write(&map_path, &map_json)?;
    Ok((g.ruby, map_json, rb_path, false, g.parse_error))
}

fn walk_rs(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(rd) = fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        let name = e.file_name().to_string_lossy().to_string();
        if name.starts_with('.') || name == "target" || name == "node_modules" {
            continue;
        }
        if p.is_dir() {
            walk_rs(&p, out);
        } else if name.ends_with(".rs") {
            out.push(p);
        }
    }
}

fn cmd_build(dir: &Path, force: bool) {
    let t0 = Instant::now();
    let root = find_root(dir);
    let cache = ensure_cache_dir(&root);
    let mut files = vec![];
    walk_rs(&dir.canonicalize().unwrap_or(dir.to_path_buf()), &mut files);

    // Pass 1: crate-wide symbol kinds (so `impl Shape` knows Shape is an enum => Ruby module)
    let mut kinds: HashMap<String, Kind> = HashMap::new();
    for f in &files {
        if let Ok(src) = fs::read_to_string(f) {
            if let Ok(ast) = syn::parse_file(&src) {
                collect_kinds(&ast.items, &mut kinds);
            }
        }
    }
    let mut merged = load_kinds(&cache);
    merged.extend(kinds);
    let sym = Symbols { kinds: merged.iter().map(|(k, v)| (k.clone(), kind_str(*v).to_string())).collect() };
    let _ = fs::write(cache.join("symbols.json"), serde_json::to_string_pretty(&sym).unwrap());

    // Pass 2: generate in parallel
    let fresh = AtomicUsize::new(0);
    let cached = AtomicUsize::new(0);
    let errors = std::sync::Mutex::new(vec![]);
    let workers = std::thread::available_parallelism().map(|n| n.get()).unwrap_or(4);
    let chunk = files.len().div_ceil(workers).max(1);
    std::thread::scope(|s| {
        for part in files.chunks(chunk) {
            let (root, merged, fresh, cached, errors) = (&root, &merged, &fresh, &cached, &errors);
            s.spawn(move || {
                for f in part {
                    match gen_cached(f, root, merged, !force) {
                        Ok((_, _, _, true, _)) => {
                            cached.fetch_add(1, Ordering::Relaxed);
                        }
                        Ok((_, _, _, false, perr)) => {
                            fresh.fetch_add(1, Ordering::Relaxed);
                            if let Some(e) = perr {
                                errors.lock().unwrap().push(format!("{}: {e}", f.display()));
                            }
                        }
                        Err(e) => errors.lock().unwrap().push(format!("{}: {e}", f.display())),
                    }
                }
            });
        }
    });
    let errors = errors.into_inner().unwrap();
    eprintln!(
        "rbview: {} files ({} generated, {} unchanged) into {} in {:.2?}",
        files.len(),
        fresh.load(Ordering::Relaxed),
        cached.load(Ordering::Relaxed),
        cache.display(),
        t0.elapsed()
    );
    for e in &errors {
        eprintln!("  fallback (raw source): {e}");
    }
}

fn collect_kinds(items: &[syn::Item], m: &mut HashMap<String, Kind>) {
    for it in items {
        match it {
            syn::Item::Struct(s) => {
                m.insert(s.ident.to_string(), Kind::Struct);
            }
            syn::Item::Enum(e) => {
                m.insert(e.ident.to_string(), Kind::Enum);
            }
            syn::Item::Trait(t) => {
                m.insert(t.ident.to_string(), Kind::Trait);
            }
            syn::Item::Mod(syn::ItemMod { content: Some((_, items)), .. }) => collect_kinds(items, m),
            _ => {}
        }
    }
}

fn usage() -> ! {
    eprintln!(
        "rbview — read Rust code as Ruby\n\n\
         USAGE:\n  \
         rbview gen <file.rs> [--root DIR] [--json] [--no-cache]   print the Ruby view of one file\n  \
         rbview build [DIR] [--force]                              pre-generate views for every .rs file\n\n\
         Views are cached in <repo>/.rbview/ (self-gitignored)."
    );
    std::process::exit(2)
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let Some(cmd) = args.first() else { usage() };
    let flag = |f: &str| args.iter().any(|a| a == f);
    let opt = |f: &str| args.iter().position(|a| a == f).and_then(|i| args.get(i + 1)).cloned();
    let positional: Vec<&String> = {
        let mut v = vec![];
        let mut skip = false;
        for a in &args[1..] {
            if skip {
                skip = false;
                continue;
            }
            if a == "--root" {
                skip = true;
                continue;
            }
            if !a.starts_with("--") {
                v.push(a);
            }
        }
        v
    };
    match cmd.as_str() {
        "gen" => {
            let Some(file) = positional.first() else { usage() };
            let file = PathBuf::from(file).canonicalize().unwrap_or_else(|e| {
                eprintln!("rbview: {file}: {e}");
                std::process::exit(1)
            });
            let root = opt("--root").map(PathBuf::from).unwrap_or_else(|| find_root(&file));
            let root = root.canonicalize().unwrap_or(root);
            let kinds = load_kinds(&root.join(CACHE_DIR));
            match gen_cached(&file, &root, &kinds, !flag("--no-cache")) {
                Ok((ruby, map, rb_path, from_cache, _)) => {
                    if flag("--json") {
                        println!(
                            "{{\"rbPath\":{},\"cached\":{},\"ruby\":{},\"map\":{}}}",
                            serde_json::to_string(&rb_path.to_string_lossy()).unwrap(),
                            from_cache,
                            serde_json::to_string(&ruby).unwrap(),
                            map
                        );
                    } else {
                        print!("{ruby}");
                    }
                }
                Err(e) => {
                    eprintln!("rbview: {e}");
                    std::process::exit(1)
                }
            }
        }
        "build" => {
            let dir = positional.first().map(PathBuf::from).unwrap_or_else(|| PathBuf::from("."));
            cmd_build(&dir, flag("--force"));
        }
        _ => usage(),
    }
}
